const {test}=require('node:test');
const assert=require('node:assert/strict');
const http=require('node:http');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {spawn}=require('node:child_process');

test('access API requires Calendar identity, admin role, origin and CSRF',async t=>{
  const data=fs.mkdtempSync(path.join(os.tmpdir(),'garyhub-access-api-'));
  const token='a'.repeat(64);
  const auth=http.createServer((req,res)=>{
    const id=Number((req.headers.cookie||'').replace('id=',''));
    res.setHeader('Content-Type','application/json');
    if(req.url==='/api/csrf')return res.end(JSON.stringify({token}));
    if(![1,2].includes(id)){res.writeHead(401);return res.end('{}');}
    return res.end(JSON.stringify({user:{id,username:`user${id}`,role:id===2?'admin':'user'}}));
  });
  await new Promise(resolve=>auth.listen(0,'127.0.0.1',resolve));
  const free=http.createServer();await new Promise(resolve=>free.listen(0,'127.0.0.1',resolve));const port=free.address().port;await new Promise(resolve=>free.close(resolve));
  const runtimeFile=path.join(data,'runtime.json');
  const proc=spawn(process.execPath,[path.join(__dirname,'../server.cjs')],{env:{...process.env,PORT:String(port),LAB_DATA_DIR:data,ACCESS_RUNTIME_FILE:runtimeFile,CALENDAR_URL:`http://127.0.0.1:${auth.address().port}`,PUBLIC_ORIGIN:'https://lab.garyhub.uk'},stdio:'ignore'});
  t.after(async()=>{proc.kill();await new Promise(resolve=>auth.close(resolve));fs.rmSync(data,{recursive:true,force:true});});
  const root=`http://127.0.0.1:${port}`;
  for(let i=0;i<80;i++){try{if((await fetch(root+'/health')).ok)break;}catch{}await new Promise(resolve=>setTimeout(resolve,25));}
  const call=(route,id,method='GET',value,headers={})=>fetch(root+route,{method,redirect:'manual',headers:{cookie:id?`id=${id}`:'',origin:'https://lab.garyhub.uk','x-csrf-token':token,'content-type':'application/json',...headers},body:value?JSON.stringify(value):undefined});
  assert.equal((await call('/access/')).status,302);
  assert.equal((await call('/api/access/status')).status,401);
  assert.equal((await call('/api/access/status',1)).status,200);
  assert.equal((await call('/api/access/admin/codes',1)).status,403);
  assert.equal((await call('/api/access/admin/codes',2,'POST',{duration:7,count:1},{origin:'https://evil.example'})).status,403);
  assert.equal((await call('/api/access/admin/codes',2,'POST',{duration:7,count:1},{'x-csrf-token':'b'.repeat(64)})).status,403);
  const generated=await call('/api/access/admin/codes',2,'POST',{duration:7,count:1});assert.equal(generated.status,201);
  const code=(await generated.json()).codes[0];
  const redeemed=await call('/api/access/redeem',1,'POST',{code});
  assert.equal(redeemed.status,200);
  const publicGrant=(await redeemed.json()).grant;
  assert.equal(publicGrant.clientId,undefined);
  assert.equal(publicGrant.subscriptionToken,undefined);
  assert.equal((await call('/api/access/redeem',2,'POST',{code})).status,400);
  assert.equal((await (await call('/api/access/status',2)).json()).grant,null);
  assert.equal((await (await call('/api/access/status',1)).json()).grant.connectionStatus,'pending');
  const privateGrant=()=>JSON.parse(fs.readFileSync(path.join(data,'access-entitlements.json'),'utf8')).grants['1'];
  const sync=()=>fs.writeFileSync(runtimeFile,JSON.stringify({ok:true,updatedAt:new Date().toISOString(),host:'vpn.garyhub.uk',wsPath:'/test',clients:{1:privateGrant().clientId}}));
  sync();
  const connected=(await (await call('/api/access/status',1)).json()).grant;
  assert.equal(connected.connectionStatus,'ready');
  const subscription=new URL(connected.subscriptionUrl).pathname;
  const response=await call(subscription);assert.equal(response.status,200);
  assert.match(Buffer.from(await response.text(),'base64').toString(),/^vless:\/\//);
  assert.equal((await call('/api/access/admin/settings',1,'POST',{storeUrl:'https://example.com'})).status,403);
  assert.equal((await call('/api/access/admin/settings',2,'POST',{storeUrl:'javascript:alert(1)'})).status,400);
  assert.equal((await call('/api/access/admin/settings',2,'POST',{storeUrl:'https://example.com/shop'})).status,200);
  assert.equal((await (await call('/api/access/status',1)).json()).storeUrl,'https://example.com/shop');
  const listed=await (await call('/api/access/admin/grants',2)).json();
  assert.equal(listed.grants[0].subscriptionToken,undefined);
  assert.equal(listed.grants[0].clientId,undefined);
  assert.equal((await call('/api/access/rotate',1,'POST',{})).status,200);
  assert.equal((await call(subscription)).status,404);
  assert.equal((await (await call('/api/access/status',1)).json()).grant.connectionStatus,'pending');
  sync();
  const rotated=(await (await call('/api/access/status',1)).json()).grant;
  assert.notEqual(rotated.connectionUri,connected.connectionUri);
  const newSub=new URL(rotated.subscriptionUrl).pathname;
  assert.equal((await call(newSub)).status,200);
  assert.equal((await call('/api/access/admin/revoke',1,'POST',{userId:1})).status,403);
  assert.equal((await call('/api/access/admin/revoke',2,'POST',{userId:1},{'x-csrf-token':'b'.repeat(64)})).status,403);
  assert.equal((await call('/api/access/admin/revoke',2,'POST',{userId:1})).status,200);
  assert.equal((await call(newSub)).status,404);
  assert.equal((await (await call('/api/access/status',1)).json()).grant.active,false);
});
